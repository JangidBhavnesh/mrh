"""Fixed-orbital periodic LAS state interaction without translation adaptation.

Product states use fragment-major fermion ordering: alpha then beta orbitals
within each fragment. Integrals use the spatial-orbital chemists' convention.
Matrix elements are contracted from local transition tensors, without expanding
the product states into the full-supercell determinant space.
"""

from itertools import product

import numpy as np
from scipy import linalg
from pyscf import lib
from pyscf.fci import addons, cistring

from mrh.my_pyscf.pbc.mcscf.klasci import PBCLASCINoSymm, kLASCI
from mrh.my_pyscf.pbc.mcscf import klassi_trans


def _apply_local(ci, norb, nelec, spin, create, orbital):
    """Apply a local fermion operator, retaining complex CI coefficients."""
    operation = ((addons.des_a, addons.des_b),
                 (addons.cre_a, addons.cre_b))[create][spin]
    return (operation(ci.real, norb, nelec, orbital)
            + 1j * operation(ci.imag, norb, nelec, orbital))


class _ProductTransition:
    """Cache fragment transition tensors for one bra/ket product pair."""

    def __init__(self, bra, ket, norb, nelec_bra, nelec_ket):
        self.bra, self.ket = bra, ket
        self.norb = norb
        self.nelec_bra = np.asarray(nelec_bra)
        self.nelec_ket = np.asarray(nelec_ket)
        self.cache = {}

    def local_tensor(self, frag, operators):
        key = (frag, tuple(operators))
        if key in self.cache:
            return self.cache[key]
        norb = self.norb[frag]
        tensor = np.zeros((norb,) * len(operators), dtype=complex)
        for orbitals in np.ndindex(tensor.shape):
            ci = self.ket[frag]
            nelec = self.nelec_ket[frag].copy()
            for (spin, create), orbital in reversed(list(zip(operators, orbitals))):
                if (create and nelec[spin] == norb) or (not create and nelec[spin] == 0):
                    ci = None
                    break
                ci = _apply_local(ci, norb, tuple(nelec), spin, create, orbital)
                nelec[spin] += 1 if create else -1
            if ci is not None:
                tensor[orbitals] = np.vdot(self.bra[frag], ci)
        self.cache[key] = tensor
        return tensor

    def contract(self, integrals, operators):
        """Contract operators (fragment, spin, creation, integral-axis label)."""
        nelec = self.nelec_ket.copy()
        sign = 1
        # Jordan-Wigner parity follows the occupations at each operator action.
        for frag, spin, create, _ in reversed(operators):
            if (create and nelec[frag, spin] == self.norb[frag]
                    or not create and nelec[frag, spin] == 0):
                return 0j
            if nelec[:frag].sum() % 2:
                sign = -sign
            nelec[frag, spin] += 1 if create else -1
        if not np.array_equal(nelec, self.nelec_bra):
            return 0j
        args = [integrals, list(range(integrals.ndim))]
        for frag in range(len(self.norb)):
            local = [(spin, create) for f, spin, create, _ in operators if f == frag]
            labels = [label for f, _, _, label in operators if f == frag]
            args.extend((self.local_tensor(frag, local), labels))
        return sign * np.einsum(*args, [], optimize=True)


def ham_2q(las, mo_coeff=None):
    """Return (ecore, h1, h2) in the full-supercell Wannier active space."""
    if mo_coeff is None:
        mo_coeff = las.mo_coeff
    h1, ecore = las.h1e_for_cas(mo_coeff=mo_coeff)
    return ecore, h1, las.get_h2cas(mo_coeff)


def make_charged_states(las, charge, mo_coeff=None, charged_spin=None,
                        charged_spin_mult=None):
    """Independently solve one charged LAS reference for each Wannier cell.

    las supplies the neutral partition, common orbitals, and CI convergence
    settings. Each reference optimizes *all* its fragment CI vectors afresh;
    no state is copied or generated by translating another charged state.
    Currently supports one root and identical neutral fragment quantum numbers.
    """
    if not isinstance(charge, (int, np.integer)) or charge not in (-1, 1):
        raise ValueError("charged kLASSI requires charge +1 or -1")
    if getattr(las, 'charge', 0) or las.nroots != 1:
        raise ValueError("supply a neutral, single-root LAS reference")
    nelec = las.get_nelec_frs()[:, 0]
    smults = [box.fcisolvers[0].smult for box in las.fciboxes]
    if (np.any(las.ncas_sub != las.ncas) or np.any(nelec != las.nelecas)
            or any(s != smults[0] for s in smults)):
        raise ValueError("neutral fragments must have identical orbital, electron, and spin sectors")
    if mo_coeff is None:
        mo_coeff = las.mo_coeff
    mo_coeff = np.asarray(mo_coeff)
    if (mo_coeff.ndim != 3 or mo_coeff.shape[0] != las.nkpts
            or mo_coeff.shape[1] != las.cell.nao_nr()
            or mo_coeff.shape[2] < las.ncore + las.ncas):
        raise ValueError("mo_coeff must contain common k-point core and active orbitals")
    states = []
    for ref_cell in range(las.nfrags):
        state = kLASCI(las._scf, las.ncas, las.nelecas, ncore=las.ncore,
                       spin_mult=smults[0], kmesh=las.kmesh, charge=charge,
                       ref_cell=ref_cell, charged_spin=charged_spin,
                       charged_spin_mult=charged_spin_mult)
        for attr in ('verbose', 'stdout', 'max_memory', 'conv_tol_grad',
                     'conv_tol_self', 'max_cycle_macro'):
            setattr(state, attr, getattr(las, attr))
        lib.logger.info(las, "Solving charge %+d independently on cell %d", charge, ref_cell)
        state.kernel(mo_coeff.copy())
        if not state.converged:
            raise RuntimeError(f"charged LASCI did not converge on reference cell {ref_cell}")
        states.append(state)
    return states


def build_hamiltonian(h1, h2, ci, ncas_sub, nelec_frs, ecore=0):
    """Build complex H and S from single-root LAS product states.

    ci[fragment][state] contains a determinant-basis fragment CI matrix;
    nelec_frs has shape (nfrags, nstates, 2). All states must have the same
    total alpha and beta counts and use the same orthonormal orbital set.
    H includes ecore*S and is in full-supercell energy units.

    This general fragment-contraction implementation prioritizes correctness;
    it visits all one- and two-electron fragment blocks and screens forbidden
    electron transfers before constructing local transition tensors.
    """
    ncas_sub = np.asarray(ncas_sub, dtype=int)
    nelec_frs = np.asarray(nelec_frs)
    if (nelec_frs.ndim != 3 or nelec_frs.shape[0] != len(ncas_sub)
            or nelec_frs.shape[2] != 2 or nelec_frs.shape[1] == 0
            or not np.issubdtype(nelec_frs.dtype, np.integer)):
        raise ValueError("nelec_frs must have shape (nfrags, nstates, 2) with integer counts")
    nfrags, nstates = nelec_frs.shape[:2]
    if (np.any(ncas_sub <= 0) or np.any(nelec_frs < 0)
            or np.any(nelec_frs > ncas_sub[:, None, None])):
        raise ValueError("invalid fragment orbital or electron counts")
    totals = nelec_frs.sum(axis=0)
    if np.any(totals != totals[0]):
        raise ValueError("all LAS states must have the same total alpha and beta counts")
    norb = int(ncas_sub.sum())
    h1, h2 = np.asarray(h1), np.asarray(h2)
    if h1.shape != (norb, norb) or h2.shape != (norb,) * 4:
        raise ValueError("integral dimensions do not match the full active space")
    if len(ci) != nfrags or any(len(row) != nstates for row in ci):
        raise ValueError("ci must contain one vector per fragment and state")
    ci = [[np.asarray(c, dtype=complex) for c in row] for row in ci]
    for frag, row in enumerate(ci):
        for state, c in enumerate(row):
            shape = tuple(cistring.num_strings(ncas_sub[frag], n)
                          for n in nelec_frs[frag, state])
            if c.shape != shape or not np.all(np.isfinite(c)):
                raise ValueError("fragment CI shape or values are invalid")
    offsets = np.concatenate(([0], np.cumsum(ncas_sub)))
    slices = [slice(i, j) for i, j in zip(offsets[:-1], offsets[1:])]
    ham = np.zeros((nstates, nstates), dtype=complex)
    ovlp = np.zeros_like(ham)
    for bra, ket in product(range(nstates), repeat=2):
        transition = _ProductTransition(
            [row[bra] for row in ci], [row[ket] for row in ci], ncas_sub,
            nelec_frs[:, bra], nelec_frs[:, ket])
        ovlp[bra, ket] = transition.contract(np.asarray(1.), [])
        for p, q in product(range(nfrags), repeat=2):
            block = h1[slices[p], slices[q]]
            for spin in range(2):
                ham[bra, ket] += transition.contract(
                    block, [(p, spin, True, 0), (q, spin, False, 1)])
        for p, q, r, s in product(range(nfrags), repeat=4):
            block = h2[slices[p], slices[q], slices[r], slices[s]]
            for sigma, tau in product(range(2), repeat=2):
                ham[bra, ket] += .5 * transition.contract(block, [
                    (p, sigma, True, 0), (r, tau, True, 2),
                    (s, tau, False, 3), (q, sigma, False, 1)])
    return ham + ecore * ovlp, ovlp


def diagonalize(ham, ovlp):
    """Solve H C = S C E, rejecting invalid or linearly dependent bases."""
    ham, ovlp = np.asarray(ham), np.asarray(ovlp)
    if (ham.ndim != 2 or ham.shape[0] != ham.shape[1]
            or ovlp.shape != ham.shape or not ham.size):
        raise ValueError("H and S must be nonempty square matrices of equal shape")
    for name, matrix in (('Hamiltonian', ham), ('overlap', ovlp)):
        if (not np.all(np.isfinite(matrix))
                or not np.allclose(matrix, matrix.conj().T, atol=1e-9, rtol=1e-10)):
            raise ValueError(f"{name} must be finite and Hermitian")
    if np.min(linalg.eigvalsh(ovlp)) <= 1e-10:
        raise ValueError("LAS overlap is not positive definite; remove dependent states")
    return linalg.eigh(ham, ovlp)


class KLASSI(lib.StreamObject):
    """Charged periodic LAS state interaction in common, fixed orbitals.

    Args:
        las: Neutral single-root kLASCI or kLASSCF object defining orbitals,
            fragment sectors, and convergence settings for the charged solves.
        charge: +1 (one hole) or -1 (one added electron) across the full mesh.
        charged_spin: N_alpha - N_beta on the charged fragment; defaults as
            in KLASCI. This is not the total supercell spin projection.
        charged_spin_mult: Charged-fragment 2S+1, as in KLASCI.

    kernel() independently optimizes one charged LAS product for every cell,
    then diagonalizes their full state-interaction matrix. No translation
    adaptation or momentum labels are used. One local root per fragment and
    one charged channel are supported initially.

    Results:
        charged_states: Separate converged KLASCI objects in reference-cell order.
        ci, nelec_frs: Fragment CI vectors and counts, indexed [fragment][state].
        ham, ovlp: Full-supercell Hamiltonian and overlap in the product basis.
        e_tot: Sorted state-interaction energies per primitive cell.
        e_tot_supercell: The corresponding full-supercell energies.
        si: Eigenvectors in columns; si.conj().T @ ovlp @ si is the identity.
        s2, spin_multiplicity: Root <S^2> and sqrt(1 + 4<S^2>). The latter
            is an effective 2S+1 for states that are not eigenstates of S^2.

    The contraction backend avoids full-supercell CI vectors but visits all
    two-electron fragment blocks. Large meshes will need a more efficient
    screened backend; no translation reduction is performed here.
    """

    _keys = {'charge', 'charged_spin', 'charged_spin_mult', 'mo_coeff',
             'ncas_sub', 'nkpts', 'ref_cells', 'charged_states', 'ci',
             'nelec_frs', 'ham', 'ovlp', 'e_tot', 'e_tot_supercell', 'si',
             's2', 'spin_multiplicity', 'converged'}

    def __init__(self, las, charge=1, charged_spin=None, charged_spin_mult=None):
        if not isinstance(las, PBCLASCINoSymm):
            raise TypeError("KLASSI requires a neutral kLASCI or kLASSCF object")
        if not isinstance(charge, (int, np.integer)) or charge not in (-1, 1):
            raise ValueError("charged kLASSI requires charge +1 or -1")
        self._las = las
        self.charge = int(charge)
        self.charged_spin = charged_spin
        self.charged_spin_mult = charged_spin_mult
        self.verbose, self.stdout, self.max_memory = las.verbose, las.stdout, las.max_memory
        self.mo_coeff = np.array(las.mo_coeff, copy=True)
        self.ncas_sub = las.ncas_sub.copy()
        self.nkpts = las.nkpts
        self.ref_cells = np.arange(las.nfrags)
        self.charged_states = []
        self.ci = self.nelec_frs = None
        self.ham = self.ovlp = self.si = None
        self.e_tot = self.e_tot_supercell = None
        self.s2 = self.spin_multiplicity = None
        self.converged = False

    def kernel(self, mo_coeff=None):
        """Return (energies per cell, SI coefficients) for one charge sector."""
        self.converged = False
        self.charged_states = []
        self.ci = self.nelec_frs = None
        self.ham = self.ovlp = self.si = None
        self.e_tot = self.e_tot_supercell = None
        self.s2 = self.spin_multiplicity = None
        if mo_coeff is not None:
            self.mo_coeff = np.array(mo_coeff, copy=True)
        self.charged_states = make_charged_states(
            self._las, self.charge, mo_coeff=self.mo_coeff,
            charged_spin=self.charged_spin, charged_spin_mult=self.charged_spin_mult)
        self.ci = [[state.ci[f][0] for state in self.charged_states]
                   for f in range(len(self.ncas_sub))]
        self.nelec_frs = np.stack(
            [state.get_nelec_frs()[:, 0] for state in self.charged_states], axis=1)
        ecore, h1, h2 = ham_2q(self._las, self.mo_coeff)
        self.ham, self.ovlp = build_hamiltonian(
            h1, h2, self.ci, self.ncas_sub, self.nelec_frs, ecore)
        reference_energies = np.asarray([s.e_tot for s in self.charged_states]) * self.nkpts
        if not np.allclose(np.diag(self.ham), reference_energies, atol=1e-8, rtol=1e-10):
            raise RuntimeError("LASSI diagonal does not reproduce the charged LAS energies")
        self.e_tot_supercell, self.si = diagonalize(self.ham, self.ovlp)
        self.e_tot = self.e_tot_supercell / self.nkpts
        self.s2, self.spin_multiplicity = self.spin_square()
        self.converged = True
        self._finalize()
        return self.e_tot, self.si

    def spin_square(self):
        """Return total <S^2> and effective multiplicity for each SI root.

        S^2 preserves every fragment's electron count, so its matrix is
        diagonal in this one-charged-state-per-cell basis. Each product has
        <S^2> = sum_f S_f(S_f+1) + 2 sum_{f<g} M_f M_g.
        """
        if self.si is None:
            raise ValueError("run kLASSI before evaluating the root spins")
        smults = np.array([[box.fcisolvers[0].smult for box in state.fciboxes]
                           for state in self.charged_states])
        ms = (self.nelec_frs[:, :, 0] - self.nelec_frs[:, :, 1]).T / 2
        product_s2 = ((smults ** 2 - 1) / 4).sum(axis=1)
        product_s2 += ms.sum(axis=1) ** 2 - (ms ** 2).sum(axis=1)
        weights = abs(self.si) ** 2 * self.ovlp.diagonal().real[:, None]
        s2 = product_s2 @ weights / weights.sum(axis=0)
        return s2, np.sqrt(1 + 4 * s2)

    def get_translation_matrix(self, translation, tol=1e-5, energy_tol=1e-7,
                               orbital_tol=1e-8):
        """Return a validated many-electron translation in lattice units.

        Example: get_translation_matrix((1, 0, 0)) translates one cell along
        the first lattice vector. This checks basis closure, H/S invariance,
        and the finite translation-group cycle. It does not assign momenta.
        """
        return klassi_trans.check_translation(
            self, translation, tol, energy_tol, orbital_tol)['matrix']

    def check_translation_symmetry(self, tol=1e-5, energy_tol=1e-7, orbital_tol=1e-8):
        """Return generator matrices and errors after checking all translations.

        Each lattice-generator key maps to matrix, overlap, closure_errors,
        overlap_error, hamiltonian_error, and group_error. energy_tol is in
        Hartree per supercell; the other error thresholds are dimensionless.
        The independent references and state-interaction results are unchanged.
        """
        return klassi_trans.check_translation_symmetry(self, tol, energy_tol, orbital_tol)

    def _finalize(self):
        log = lib.logger.new_logger(self)
        # Use actual supercell counts: positive charge removes an electron.
        nelec = int(self.nelec_frs[:, 0].sum())
        active_space = f"({nelec}, {int(self.ncas_sub.sum())})"
        log.info("\nk-LASSI charge %+d", self.charge)
        log.info("%5s  %23s  %22s  %12s", "State", "Total Active Space (e,o)",
                 "Energies (Ha/cell)", "Spin (2S+1)")
        for root, energy in enumerate(self.e_tot):
            log.info("%5d  %23s  %22.12f  %12.6f", root, active_space,
                     energy, self.spin_multiplicity[root])
        log.info("Spin (2S+1) is inferred from <S^2>; noninteger values indicate spin mixing.")
        return self


kLASSI = KLASSI
